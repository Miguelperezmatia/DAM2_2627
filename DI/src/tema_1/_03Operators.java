package tema_1;

public class _03Operators
{
    public static void main(String[] args)
    {
        int mynumber = 5;
        int myNumber2 = 3;

        System.out.println(mynumber + myNumber2);
        System.out.println(mynumber - myNumber2);
        System.out.println(mynumber * myNumber2);
        System.out.println(mynumber / myNumber2);
        System.out.println(mynumber % myNumber2);
        System.out.println((double) mynumber / myNumber2);  //  Para que nos de decimales hay que pasar a double
    }
}
