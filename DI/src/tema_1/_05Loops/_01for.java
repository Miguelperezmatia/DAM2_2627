package tema_1._05Loops;

public class _01for
{
    public static void main(String[] args)
    {
        for(int i = 1; i < 10; i++)
            System.out.println(i);

        String [] names = {"Miguel", "Manolo", "Laura"};

        for (int i = 0; i < names.length; i++)
            System.out.println(names[i]);

    }
}
