package tema_1._01Base;

public class _04Conditionals
{
    public static void main(String[] args)
    {
        int edad = 18;

        if(edad > 18)
            System.out.println("Es mayor");
        else if(edad == 18)
            System.out.println("Tiene 18");
        else
            System.out.println("Es menor");
    }
}
